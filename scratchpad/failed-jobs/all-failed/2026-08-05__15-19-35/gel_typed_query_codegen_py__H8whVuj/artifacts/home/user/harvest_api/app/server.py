"""Small local JSON HTTP service exposing the harvest-tracking queries.

No EdgeQL text or parameter casts appear anywhere in this module (or any
hand-written module outside app/queries/). All database access goes through
the statically typed functions generated by Gel's Python code generator from
the .edgeql files in app/queries/.
"""

from __future__ import annotations

import json
import re
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, unquote

import gel

from app.queries.list_region_growers_edgeql import list_region_growers
from app.queries.get_batch_detail_edgeql import get_batch_detail
from app.queries.record_inspection_edgeql import record_inspection
from app.queries.region_totals_edgeql import region_totals

HOST = "127.0.0.1"
PORT = 8099

_BATCH_PATH_RE = re.compile(r"^/batches/([^/]+)$")

_client = gel.create_client()


# --------------------------------------------------------------------------
# Small helpers
# --------------------------------------------------------------------------

def _is_non_empty_str(value) -> bool:
    return isinstance(value, str) and len(value) > 0


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _validate_string_array(value, max_len=None):
    """Return the (list) value if it is a list of non-empty strings within
    the optional max length, otherwise None."""
    if not isinstance(value, list):
        return None
    if max_len is not None and len(value) > max_len:
        return None
    for item in value:
        if not _is_non_empty_str(item):
            return None
    return value


class InvalidRequest(Exception):
    pass


class NotFound(Exception):
    pass


class BatchNotFound(Exception):
    pass


# --------------------------------------------------------------------------
# Route handlers. Each returns (status, payload_dict).
# --------------------------------------------------------------------------

def _require_object(data):
    if not isinstance(data, dict):
        raise InvalidRequest()
    return data


def handle_healthz():
    return 200, {"status": "ok"}


def handle_growers_search(data):
    data = _require_object(data)

    region_code = data.get("region_code")
    if not _is_non_empty_str(region_code):
        raise InvalidRequest()

    min_kilograms = None
    if "min_kilograms" in data and data["min_kilograms"] is not None:
        raw = data["min_kilograms"]
        if not _is_number(raw):
            raise InvalidRequest()
        min_kilograms = float(raw)

    certifications = []
    if "certifications" in data and data["certifications"] is not None:
        certifications = _validate_string_array(data["certifications"], max_len=8)
        if certifications is None:
            raise InvalidRequest()

    rows = list_region_growers(
        _client,
        region_code=region_code,
        min_kilograms=min_kilograms,
        certifications=certifications,
    )

    growers = []
    for g in rows:
        batches = []
        matched_kilograms = 0
        for b in g.batches:
            batches.append(
                {
                    "code": b.code,
                    "kilograms": b.kilograms,
                    "harvested_on": b.harvested_on.isoformat(),
                    "certifications": sorted(b.certifications),
                }
            )
            matched_kilograms += b.kilograms
        growers.append(
            {
                "slug": g.slug,
                "name": g.name,
                "region": {"code": g.region.code, "name": g.region.name},
                "batches": batches,
                "matched_batches": len(batches),
                "matched_kilograms": matched_kilograms,
            }
        )

    return 200, {"region_code": region_code, "growers": growers}


def handle_get_batch(code):
    row = get_batch_detail(_client, code=code)
    if row is None:
        raise NotFound()

    payload = {
        "code": row.code,
        "kilograms": row.kilograms,
        "harvested_on": row.harvested_on.isoformat(),
        "certifications": sorted(row.certifications),
        "grower": {
            "slug": row.grower.slug,
            "name": row.grower.name,
            "region": {
                "code": row.grower.region.code,
                "name": row.grower.region.name,
            },
        },
        "inspection_count": row.inspection_count,
    }
    return 200, payload


def handle_inspections(data):
    data = _require_object(data)

    for key in ("batch_code", "inspector", "passed", "defect_codes", "severity"):
        if key not in data:
            raise InvalidRequest()

    batch_code = data["batch_code"]
    inspector = data["inspector"]
    passed = data["passed"]
    defect_codes = data["defect_codes"]
    severity = data["severity"]

    if not _is_non_empty_str(batch_code):
        raise InvalidRequest()
    if not _is_non_empty_str(inspector):
        raise InvalidRequest()
    if not isinstance(passed, bool):
        raise InvalidRequest()
    defect_codes = _validate_string_array(defect_codes, max_len=8)
    if defect_codes is None:
        raise InvalidRequest()
    if not _is_int(severity) or severity < 1 or severity > 5:
        raise InvalidRequest()

    try:
        result = record_inspection(
            _client,
            batch_code=batch_code,
            inspector=inspector,
            passed=passed,
            defect_codes=defect_codes,
            severity=severity,
        )
    except gel.errors.MissingRequiredError:
        raise BatchNotFound()

    payload = {
        "inspection_id": str(result.id),
        "batch_code": result.batch_code,
        "inspector": result.inspector,
        "passed": result.passed,
        "defect_count": result.defect_count,
    }
    return 201, payload


def handle_regions_totals(data):
    data = _require_object(data)

    region_codes = []
    if "region_codes" in data and data["region_codes"] is not None:
        region_codes = _validate_string_array(data["region_codes"])
        if region_codes is None:
            raise InvalidRequest()

    rows = region_totals(_client, region_codes=region_codes)

    regions = [
        {
            "code": r.code,
            "name": r.name,
            "grower_count": r.grower_count,
            "batch_count": r.batch_count,
            "total_kilograms": r.total_kilograms,
        }
        for r in rows
    ]
    return 200, {"regions": regions}


# --------------------------------------------------------------------------
# HTTP plumbing
# --------------------------------------------------------------------------

class Handler(BaseHTTPRequestHandler):
    server_version = "HarvestAPI/1.0"

    def log_message(self, format, *args):  # noqa: A002 - silence default logging
        pass

    def _send_json(self, status, payload):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except BrokenPipeError:
            pass

    def _read_json_body(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length > 0 else b""
        if not raw:
            raise InvalidRequest()
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            raise InvalidRequest()

    def _dispatch(self, method):
        parsed = urlparse(self.path)
        path = parsed.path

        try:
            if method == "GET" and path == "/healthz":
                status, payload = handle_healthz()
            elif method == "POST" and path == "/growers/search":
                status, payload = handle_growers_search(self._read_json_body())
            elif method == "GET" and _BATCH_PATH_RE.match(path):
                code = unquote(_BATCH_PATH_RE.match(path).group(1))
                status, payload = handle_get_batch(code)
            elif method == "POST" and path == "/inspections":
                status, payload = handle_inspections(self._read_json_body())
            elif method == "POST" and path == "/regions/totals":
                status, payload = handle_regions_totals(self._read_json_body())
            else:
                status, payload = 404, {"error": "not_found"}
        except InvalidRequest:
            status, payload = 400, {"error": "invalid_request"}
        except NotFound:
            status, payload = 404, {"error": "not_found"}
        except BatchNotFound:
            status, payload = 404, {"error": "batch_not_found"}

        self._send_json(status, payload)

    def do_GET(self):
        self._dispatch("GET")

    def do_POST(self):
        self._dispatch("POST")


def main():
    server = ThreadingHTTPServer((HOST, PORT), Handler)
    try:
        server.serve_forever()
    finally:
        server.server_close()
        _client.close()


if __name__ == "__main__":
    main()
